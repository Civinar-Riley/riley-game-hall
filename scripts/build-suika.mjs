import { build, transform } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const source = new URL('src/games/suika/', root);
const output = new URL('public/games/suika.html', root);
const [template, css, threeLicense, matterLicense] = await Promise.all([
  readFile(new URL('game.html', source), 'utf8'),
  readFile(new URL('style.css', source), 'utf8'),
  readFile(new URL('node_modules/three/LICENSE', root), 'utf8'),
  readFile(new URL('node_modules/matter-js/LICENSE', root), 'utf8'),
]);
const result = await build({
  entryPoints: [fileURLToPath(new URL('main.js', source))],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  legalComments: 'inline',
  charset: 'utf8',
  banner: { js: `/*! Bundled third-party licenses\n\nThree.js\n${threeLicense}\nMatter.js\n${matterLicense}\n*/` },
});
const styles = await transform(css, { loader: 'css', minify: true, target: ['chrome100', 'safari15'] });
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = template
  .replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by scripts/build-suika.mjs; edit src/games/suika/ instead. -->')
  .replace('/* ORCHARD_STYLES */', () => styles.code)
  .replace('/* ORCHARD_SCRIPT */', () => script);
await mkdir(new URL('public/games/', root), { recursive: true });
let previous;
try { previous = await readFile(output, 'utf8'); } catch {}
if (previous !== html) await writeFile(output, html);
console.log(`Suika: self-contained HTML, ${(Buffer.byteLength(html) / 1024).toFixed(1)} KiB`);
