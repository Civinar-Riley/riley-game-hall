import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';

const root = new URL('../', import.meta.url);
const html = await readFile(new URL('public/games/suika.html', root), 'utf8');
const hall = await readFile(new URL('src/hall/hall.js', root), 'utf8');

test('suika is registered once and the generated game has no external script or stylesheet', () => {
  assert.equal([...hall.matchAll(/file: 'suika\.html'/g)].length, 1);
  assert.match(hall, /'suika\.html': '#648b45'/);
  assert.match(html, /Generated by scripts\/build-suika\.mjs/);
  assert.doesNotMatch(html, /ORCHARD_STYLES|ORCHARD_SCRIPT/);
  assert.doesNotMatch(html, /<script\b[^>]*\bsrc\s*=/i);
  assert.doesNotMatch(html, /<link\b[^>]*\brel=["']stylesheet/i);
  assert.equal([...html.matchAll(/<script\b/g)].length, 1);
  assert.equal([...html.matchAll(/<\/script>/g)].length, 1);
});

test('suika ships third-party attribution and both gameplay modes', () => {
  assert.match(html, /Copyright © 2010-2026 three\.js authors/);
  assert.match(html, /Copyright \(c\) Liam Brummitt and contributors/);
  assert.match(html, /id="classicMode"/);
  assert.match(html, /id="collectMode"/);
  assert.match(html, /id="fruitCanvas"/);
  assert.match(html, /id="confirmDialog"/);
  assert.match(html, /id="themeButton"/);
  assert.match(html, /id="themeMeta"/);
  assert.match(html, /data-theme/);
  assert.match(html, /prefers-reduced-motion/);
});
